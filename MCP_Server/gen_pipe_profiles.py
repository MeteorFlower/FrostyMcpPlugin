# Generate the pipe suffix table from Frosty's profile database.
#
# FrostySdk/Profiles.bin is the authoritative list of profiles the editor can
# load.  Read it once at build time and emit:
#
#   Bridge/PipeProfiles.g.cs      compiled into the plugin
#   MCP_Server/pipe_profiles.json read by the Python MCP server
#
# The pipe name is Frosty_MCP_Bridge_v1_<profile name>.  No game names live in
# the source; this table is the only list of profile names.
#
# Usage: python gen_pipe_profiles.py [--profiles-bin PATH]

import argparse
import json
import os
import struct
import sys

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
DEFAULT_PROFILES_BIN = os.path.abspath(
    os.path.join(REPO_ROOT, "..", "..", "FrostySdk", "Profiles.bin")
)
CS_OUT = os.path.join(REPO_ROOT, "Bridge", "PipeProfiles.g.cs")
JSON_OUT = os.path.join(REPO_ROOT, "MCP_Server", "pipe_profiles.json")
PIPE_PREFIX = "Frosty_MCP_Bridge_v1"

# Profiles.bin strings are XOR-obfuscated with the diagonal of this key.
KEY = (0x46, 0x52, 0x4F, 0x53, 0x54, 0x59)


class ProfileDbError(Exception):
    pass


def read_7bit(data, offset):
    value = 0
    shift = 0
    while True:
        if offset >= len(data):
            raise ProfileDbError("truncated 7-bit integer")
        byte = data[offset]
        offset += 1
        value |= (byte & 0x7F) << shift
        if (byte >> 7) == 0:
            return value, offset
        shift += 7
        if shift > 35:
            raise ProfileDbError("7-bit integer is too long")


def decode_string(data, offset):
    length, offset = read_7bit(data, offset)
    end = offset + length
    if end > len(data):
        raise ProfileDbError("truncated string")
    raw = bytearray(data[offset:end])
    for i in range(length):
        raw[i] ^= KEY[i % len(KEY)]
    try:
        return raw.decode("utf-8"), end
    except UnicodeDecodeError as exc:
        raise ProfileDbError("string is not valid UTF-8: %s" % exc)


def parse_profiles(path):
    with open(path, "rb") as fh:
        data = fh.read()
    if len(data) < 4:
        raise ProfileDbError("file is too short")

    count = struct.unpack_from("<i", data, 0)[0]
    if count <= 0 or count > 1000:
        raise ProfileDbError("unexpected profile count: %d" % count)

    offset = 4
    entries = []
    for _ in range(count):
        name, offset = decode_string(data, offset)
        if offset + 8 > len(data):
            raise ProfileDbError("truncated profile offset")
        rel_offset = struct.unpack_from("<q", data, offset)[0]
        offset += 8
        entries.append((name, rel_offset))

    objects_start = offset
    profiles = []
    for name, rel_offset in entries:
        pos = objects_start + rel_offset
        if pos < objects_start or pos >= len(data):
            raise ProfileDbError("profile offset out of range: %s" % name)
        display_name, _ = decode_string(data, pos)
        profiles.append({"name": name, "display_name": display_name})
    return profiles


def check_pipe_safe(name):
    if not name:
        raise ProfileDbError("empty profile name")
    for ch in name:
        if ch in ("\\", "\x00", "\n", "\r"):
            raise ProfileDbError("profile name is not pipe-safe: %r" % name)


def cs_string(value):
    out = []
    for ch in value:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 0x20 <= ord(ch) < 0x7F:
            out.append(ch)
        else:
            out.append("\\u%04x" % ord(ch))
    return '"' + "".join(out) + '"'


def write_cs(profiles):
    lines = []
    lines.append("// <auto-generated>")
    lines.append("// Generated by MCP_Server/gen_pipe_profiles.py from FrostySdk/Profiles.bin.")
    lines.append("// Do not edit by hand. Re-run the generator after updating Frosty.")
    lines.append("// </auto-generated>")
    lines.append("namespace FrostyMcpPlugin.Bridge")
    lines.append("{")
    lines.append("    internal static class PipeProfiles")
    lines.append("    {")
    lines.append('        internal const string BasePipeName = "%s";' % PIPE_PREFIX)
    lines.append("")
    lines.append("        // Profile names from the Frosty profile database. A profile that is")
    lines.append("        // not listed here (for example one supplied by a plugin) still gets")
    lines.append("        // its own pipe; the raw profile name is used as the suffix.")
    lines.append("        private static readonly string[] KnownProfiles =")
    lines.append("        {")
    for profile in profiles:
        lines.append("            %s," % cs_string(profile["name"]))
    lines.append("        };")
    lines.append("")
    lines.append("        internal static string PipeNameFor(string profile)")
    lines.append("        {")
    lines.append("            string canonical = CanonicalName(profile);")
    lines.append("            if (canonical == null)")
    lines.append("                canonical = profile;")
    lines.append("            return BasePipeName + \"_\" + canonical;")
    lines.append("        }")
    lines.append("")
    lines.append("        private static string CanonicalName(string profile)")
    lines.append("        {")
    lines.append("            foreach (string known in KnownProfiles)")
    lines.append("            {")
    lines.append("                if (System.String.Equals(known, profile,")
    lines.append("                        System.StringComparison.OrdinalIgnoreCase))")
    lines.append("                    return known;")
    lines.append("            }")
    lines.append("            return null;")
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    with open(CS_OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))


def write_json(profiles):
    payload = {
        "generated_from": "FrostySdk/Profiles.bin",
        "pipe_prefix": PIPE_PREFIX,
        "profiles": profiles,
    }
    with open(JSON_OUT, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(payload, fh, indent=2, ensure_ascii=False)
        fh.write("\n")


def main():
    parser = argparse.ArgumentParser(description="Generate the Frosty MCP pipe profile table.")
    parser.add_argument(
        "--profiles-bin",
        default=DEFAULT_PROFILES_BIN,
        help="Path to FrostySdk/Profiles.bin (default: the Frosty tool suite next to this repo).",
    )
    args = parser.parse_args()

    try:
        profiles = parse_profiles(args.profiles_bin)
    except (OSError, ProfileDbError) as exc:
        print("error: cannot read %s: %s" % (args.profiles_bin, exc), file=sys.stderr)
        return 1

    for profile in profiles:
        check_pipe_safe(profile["name"])

    write_cs(profiles)
    write_json(profiles)
    print("read %d profiles from %s" % (len(profiles), args.profiles_bin))
    print("wrote %s" % CS_OUT)
    print("wrote %s" % JSON_OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
